/** Lee `?tema=muertos` (y alias). Null si no hay parámetro o no se reconoce. */
export function readThemePreview(): string | null {
  if (typeof window === "undefined") return null;
  const raw = new URLSearchParams(window.location.search).get("tema");
  if (!raw) return null;
  return PREVIEW_ALIASES[raw.trim().toLowerCase()] ?? null;
}

