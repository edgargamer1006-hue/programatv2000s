/**
 * Películas y cortos de dominio público (EE. UU.) o con licencia CC,
 * hospedados en Internet Archive. Cada ficha se revisó en la página
 * del ítem (licenseurl / nota de derechos) y el mp4 respondió 206
 * con cabecera ftyp.
 *
 * La duración en minutos es el runtime real del archivo, redondeado.
 */
export interface PdWork {
  id: string;
  titulo: string;
  categoria: Category;
  sinopsis: string;
  genre: string;
  rating: Rating;
  /** Segundos del archivo, según los metadatos de Archive.org. */
  seconds: number;
  /** Página del ítem, no el archivo. */
  page: string;
  /** Lo que dice la ficha de Archive.org. */
  license: string;
  /** Identificador y nombre de archivo, para armar la URL directa. */
  identifier: string;
  file: string;
}

function dl(identifier: string, file: string): string {
  return `https://archive.org/download/${identifier}/${encodeURIComponent(file)}`;
}

