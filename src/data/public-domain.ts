const byId = new Map(PD_WORKS.map((work) => [work.id, work]));

export function pdUrl(id: string): string {
  const work = byId.get(id);
  return work ? dl(work.identifier, work.file) : "";
}

/** Cortinilla: el corto de Steamboat Willie, para que el hueco también tenga video. */
export const CORTINILLA_URL = pdUrl("steamboat-willie-1928");

export function toProgramItem(id: string, bloque: Bloque): CatalogItem {
  const work = byId.get(id);
  if (!work) throw new Error(`falta obra ${id}`);
  return {
    id: work.id,
    titulo: work.titulo,
    categoria: work.categoria,
    sinopsis: work.sinopsis,
    genre: work.genre,
    rating: work.rating,
    duration: Math.max(1, Math.round(work.seconds / 60)),
    bloque,
  };
}

export function pdCatalog(ids: string[], bloque: Bloque): CatalogItem[] {
  return ids.map((id) => toProgramItem(id, bloque));
}
